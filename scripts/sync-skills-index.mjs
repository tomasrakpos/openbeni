#!/usr/bin/env node
/**
 * Scans /skills/<skill>/SKILL.md + /skills/skills.config.json and generates a
 * lightweight startup metadata index (frontmatter only — no full SKILL.md bodies)
 * at functions/api/_lib/skills/skillsIndex.generated.ts.
 *
 * Adding a new skill later only requires:
 *   1. Dropping a folder into /skills/<name>/SKILL.md (+ optional references/)
 *   2. Assigning its category in /skills/skills.config.json
 *   3. Running `npm run skills:sync` (also runs automatically before build).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SKILLS_DIR = path.join(ROOT, "skills");
const CONFIG_PATH = path.join(SKILLS_DIR, "skills.config.json");
const OUT_PATH = path.join(
  ROOT,
  "functions",
  "api",
  "_lib",
  "skills",
  "skillsIndex.generated.ts"
);

function parseFrontmatter(raw) {
  const normalized = raw.replace(/\r\n/g, "\n");
  if (!normalized.startsWith("---\n")) {
    return { frontmatter: {}, body: normalized };
  }
  const endIdx = normalized.indexOf("\n---", 4);
  if (endIdx === -1) {
    return { frontmatter: {}, body: normalized };
  }
  const fmBlock = normalized.slice(4, endIdx);
  const body = normalized.slice(endIdx + 4).replace(/^\s*\n/, "");
  const frontmatter = {};
  let currentKey = null;

  for (const line of fmBlock.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const match = /^([A-Za-z0-9_-]+)\s*:\s*(.*)$/.exec(line);
    if (match) {
      currentKey = match[1].trim();
      let val = match[2].trim();
      if (
        (val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))
      ) {
        val = val.slice(1, -1);
      }
      frontmatter[currentKey] = val;
    } else if (currentKey && (line.startsWith("  ") || line.startsWith("\t"))) {
      // Multi-line folded scalar continuation
      const prev = frontmatter[currentKey] || "";
      frontmatter[currentKey] = prev ? `${prev} ${trimmed}` : trimmed;
    }
  }
  return { frontmatter, body };
}

function estimateTokens(text) {
  return Math.max(1, Math.ceil(text.length / 4));
}

function listReferenceFiles(skillDir) {
  const refDir = path.join(skillDir, "references");
  if (!fs.existsSync(refDir)) return [];
  const results = [];
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (/\.(md|txt|json)$/i.test(entry.name)) {
        results.push(path.relative(skillDir, full).replace(/\\/g, "/"));
      }
    }
  }
  walk(refDir);
  return results.sort();
}

function main() {
  if (!fs.existsSync(CONFIG_PATH)) {
    throw new Error(`Missing skills config file at ${CONFIG_PATH}`);
  }
  const config = JSON.parse(fs.readFileSync(CONFIG_PATH, "utf8"));
  const entries = [];

  for (const dirEnt of fs
    .readdirSync(SKILLS_DIR, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))) {
    if (!dirEnt.isDirectory()) continue;
    const folderName = dirEnt.name;
    const skillDir = path.join(SKILLS_DIR, folderName);
    const skillMdPath = path.join(skillDir, "SKILL.md");
    if (!fs.existsSync(skillMdPath)) continue;

    const raw = fs.readFileSync(skillMdPath, "utf8");
    const { frontmatter } = parseFrontmatter(raw);
    const cfg = config.skills?.[folderName] || {};
    const references = listReferenceFiles(skillDir);

    entries.push({
      id: folderName,
      name: frontmatter.name || folderName,
      description: String(frontmatter.description || "").slice(0, 320),
      license: frontmatter.license || undefined,
      category: cfg.category || "other",
      extraCategories: Array.isArray(cfg.extraCategories)
        ? cfg.extraCategories
        : undefined,
      priority: typeof cfg.priority === "number" ? cfg.priority : 100,
      core: Boolean(cfg.core),
      engine: cfg.engine || undefined,
      tags: Array.isArray(cfg.tags) ? cfg.tags : [],
      estimatedTokens: estimateTokens(raw),
      skillPath: `${folderName}/SKILL.md`,
      references,
    });
  }

  let designMdIndex = [];
  const designMdIndexPath = path.join(
    SKILLS_DIR,
    "awesome-design-md",
    "index.json"
  );
  if (fs.existsSync(designMdIndexPath)) {
    designMdIndex = JSON.parse(fs.readFileSync(designMdIndexPath, "utf8"));
  }

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  const generated = `// AUTO-GENERATED by scripts/sync-skills-index.mjs — DO NOT EDIT MANUALLY.
// Contains ONLY lightweight startup metadata (frontmatter + config) and the
// awesome-design-md brand index. Full SKILL.md and references/ are loaded lazily.

import type { DesignMdIndexEntry, SkillConfig, SkillMetadata } from "./types";

export const SKILLS_CONFIG: SkillConfig = ${JSON.stringify(
    {
      version: config.version,
      defaults: config.defaults,
      providerModes: config.providerModes,
      modelModes: config.modelModes,
      categoryPriorityNotes: config.categoryPriorityNotes,
    },
    null,
    2
  )};

export const SKILLS_METADATA_INDEX: SkillMetadata[] = ${JSON.stringify(
    entries,
    null,
    2
  )};

export const DESIGN_MD_INDEX: DesignMdIndexEntry[] = ${JSON.stringify(
    designMdIndex,
    null,
    2
  )};
`;

  fs.writeFileSync(OUT_PATH, generated, "utf8");
  console.log(
    `[skills:sync] Indexed ${entries.length} skills and ${designMdIndex.length} DESIGN.md entries -> ${path.relative(
      ROOT,
      OUT_PATH
    )} (${Math.round(Buffer.byteLength(generated, "utf8") / 1024)} KB)`
  );
}

main();
