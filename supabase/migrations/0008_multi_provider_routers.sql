-- OpenHarneks / apiset-pro — Multi-Provider Free Routers & Hidden-Model Independence
-- Run after 0007_token_credits.sql in the Supabase SQL editor (or `supabase db push`).
--
-- What this migration updates:
--   1. Adds `provider_ids uuid[]` and `user_provider_ids uuid[]` to `public.routers`
--      so both admin public routers and user personal routers can pool verified free
--      models across any number of selected providers (1, 2, 3, ...).
--   2. Backfills existing single-provider routers into the new array columns while
--      keeping `provider_id` / `user_provider_id` synchronized as the primary provider.
--   3. Switches single-provider FKs to `ON DELETE SET NULL` and adds cleanup triggers
--      so deleting one provider from a multi-provider router only removes that provider
--      instead of destroying the entire router (deleting the router only if 0 providers
--      remain).
--   4. Fixes `sync_catalog_model_router_membership()` so hiding a catalog model
--      (`enabled = false`) NEVER removes it from admin free routers — only marking it
--      paid, unverified, or non-free removes it — and attaches eligible free models to
--      every admin router that includes `new.provider_id` in `provider_ids`.
--   5. Updates `sync_user_model_router_membership()` for multi-provider user routers.
--   6. Backfills `router_members` for existing admin free routers so any previously
--      hidden verified free models are re-attached immediately.

-- ---------------------------------------------------------------------------
-- 1. Multi-provider array columns on `public.routers`
-- ---------------------------------------------------------------------------
alter table public.routers
  add column if not exists provider_ids uuid[] not null default '{}',
  add column if not exists user_provider_ids uuid[] not null default '{}';

update public.routers
set provider_ids = array[provider_id]
where owner_user_id is null
  and provider_id is not null
  and coalesce(array_length(provider_ids, 1), 0) = 0;

update public.routers
set user_provider_ids = array[user_provider_id]
where owner_user_id is not null
  and user_provider_id is not null
  and coalesce(array_length(user_provider_ids, 1), 0) = 0;

-- Drop old single-provider check constraint (name generated by Postgres in 0006)
do $$
declare
  c_name text;
begin
  for c_name in
    select conname
    from pg_constraint
    where conrelid = 'public.routers'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%provider_id is not null%'
  loop
    execute format('alter table public.routers drop constraint if exists %I', c_name);
  end loop;
end
$$;

alter table public.routers
  drop constraint if exists routers_scope_providers_check;

alter table public.routers
  add constraint routers_scope_providers_check check (
    (
      owner_user_id is null
      and user_provider_id is null
      and coalesce(array_length(user_provider_ids, 1), 0) = 0
      and (provider_id is not null or coalesce(array_length(provider_ids, 1), 0) >= 1)
    )
    or (
      owner_user_id is not null
      and provider_id is null
      and coalesce(array_length(provider_ids, 1), 0) = 0
      and (user_provider_id is not null or coalesce(array_length(user_provider_ids, 1), 0) >= 1)
    )
  );

-- Switch FKs from ON DELETE CASCADE to ON DELETE SET NULL so removing one
-- provider from a multi-provider router preserves the remaining providers.
alter table public.routers
  drop constraint if exists routers_provider_id_fkey;
alter table public.routers
  add constraint routers_provider_id_fkey
  foreign key (provider_id) references public.providers (id) on delete set null;

alter table public.routers
  drop constraint if exists routers_user_provider_id_fkey;
alter table public.routers
  add constraint routers_user_provider_id_fkey
  foreign key (user_provider_id) references public.user_providers (id) on delete set null;

create index if not exists routers_provider_ids_gin_idx
  on public.routers using gin (provider_ids);

create index if not exists routers_user_provider_ids_gin_idx
  on public.routers using gin (user_provider_ids);

-- ---------------------------------------------------------------------------
-- 2. Provider deletion cleanup triggers (preserve multi-provider routers)
-- ---------------------------------------------------------------------------
create or replace function public.cleanup_routers_on_provider_delete()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.routers
  set
    provider_ids = array_remove(provider_ids, old.id),
    provider_id = case
      when provider_id = old.id then (array_remove(provider_ids, old.id))[1]
      else provider_id
    end
  where owner_user_id is null
    and (provider_id = old.id or old.id = any(provider_ids));

  delete from public.routers
  where owner_user_id is null
    and provider_id is null
    and coalesce(array_length(provider_ids, 1), 0) = 0;

  return old;
end;
$$;

drop trigger if exists providers_cleanup_routers on public.providers;
create trigger providers_cleanup_routers
  after delete on public.providers
  for each row execute function public.cleanup_routers_on_provider_delete();

create or replace function public.cleanup_routers_on_user_provider_delete()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.routers
  set
    user_provider_ids = array_remove(user_provider_ids, old.id),
    user_provider_id = case
      when user_provider_id = old.id then (array_remove(user_provider_ids, old.id))[1]
      else user_provider_id
    end
  where owner_user_id is not null
    and (user_provider_id = old.id or old.id = any(user_provider_ids));

  delete from public.routers
  where owner_user_id is not null
    and user_provider_id is null
    and coalesce(array_length(user_provider_ids, 1), 0) = 0;

  return old;
end;
$$;

drop trigger if exists user_providers_cleanup_routers on public.user_providers;
create trigger user_providers_cleanup_routers
  after delete on public.user_providers
  for each row execute function public.cleanup_routers_on_user_provider_delete();

-- ---------------------------------------------------------------------------
-- 3. Updated membership sync triggers (multi-provider + hidden-model safe)
-- ---------------------------------------------------------------------------
create or replace function public.sync_catalog_model_router_membership()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Admin free routers stay active on verified free models even when the model
  -- is hidden (`enabled = false`) from the public catalog list. Only unverified,
  -- paid, or unknown models are removed.
  if (new.upstream_verified = false or new.pricing <> 'free' or coalesce(new.site_paid, false) = true) then
    delete from public.router_members
    where catalog_model_id = new.id
      and exists (select 1 from public.routers r where r.id = router_members.router_id and r.type = 'free');
  else
    insert into public.router_members (router_id, catalog_model_id, position, enabled)
    select
      r.id,
      new.id,
      coalesce((select max(rm.position) + 1 from public.router_members rm where rm.router_id = r.id), 0),
      true
    from public.routers r
    where r.owner_user_id is null
      and (r.provider_id = new.provider_id or new.provider_id = any(r.provider_ids))
      and r.type = 'free'
    on conflict (router_id, catalog_model_id) where catalog_model_id is not null do update
      set enabled = true;
  end if;
  return new;
end;
$$;

drop trigger if exists catalog_models_router_sync on public.catalog_models;
create trigger catalog_models_router_sync
  after insert or update of enabled, upstream_verified, pricing, site_paid
  on public.catalog_models
  for each row execute function public.sync_catalog_model_router_membership();

create or replace function public.sync_user_model_router_membership()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (new.enabled = false or new.pricing <> 'free') then
    delete from public.router_members
    where user_model_id = new.id
      and exists (select 1 from public.routers r where r.id = router_members.router_id and r.type = 'free');
  else
    insert into public.router_members (router_id, user_model_id, position, enabled)
    select
      r.id,
      new.id,
      coalesce((select max(rm.position) + 1 from public.router_members rm where rm.router_id = r.id), 0),
      true
    from public.routers r
    where r.owner_user_id = new.user_id
      and (r.user_provider_id = new.user_provider_id or new.user_provider_id = any(r.user_provider_ids))
      and r.type = 'free'
    on conflict (router_id, user_model_id) where user_model_id is not null do update
      set enabled = true;
  end if;
  return new;
end;
$$;

drop trigger if exists user_models_router_sync on public.user_models;
create trigger user_models_router_sync
  after insert or update of enabled, pricing
  on public.user_models
  for each row execute function public.sync_user_model_router_membership();

-- ---------------------------------------------------------------------------
-- 4. Backfill router_members for any admin free routers whose hidden free
--    models were previously removed by the 0006 trigger
-- ---------------------------------------------------------------------------
insert into public.router_members (router_id, catalog_model_id, position, enabled)
select
  r.id,
  cm.id,
  row_number() over (partition by r.id order by cm.display_name asc) - 1,
  true
from public.routers r
join public.catalog_models cm
  on (cm.provider_id = r.provider_id or cm.provider_id = any(r.provider_ids))
where r.owner_user_id is null
  and r.type = 'free'
  and cm.upstream_verified = true
  and cm.pricing = 'free'
  and coalesce(cm.site_paid, false) = false
on conflict (router_id, catalog_model_id) where catalog_model_id is not null do update
  set enabled = true;
