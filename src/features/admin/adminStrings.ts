const ADMIN_DICTIONARIES: Record<Lang, Record<string, string>> = { en, fa };

function translateAdmin(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = ADMIN_DICTIONARIES[lang] ?? en;
  const value = table[key];
  if (value === undefined) return translate(lang, key, vars);
  if (!vars) return value;
  let out = value;
  for (const [name, replacement] of Object.entries(vars)) out = out.split(`{${name}}`).join(String(replacement));
  return out;
}

export function useAdminT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useSettingsStore((s) => s.settings.lang);
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => translateAdmin(lang, key, vars),
    [lang],
  );
}
