export const DICTIONARIES: Record<Lang, Dict> = { en, fa };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = DICTIONARIES[lang] ?? en;
  let value = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useSettingsStore((s) => s.settings.lang);
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang],
  );
}

export function dirForLang(_lang: Lang): "rtl" | "ltr" {
  return "ltr";
}

/**
 * Keep the document language in sync. Layout direction stays LTR so switching
 * to Persian only changes text/locale, not element placement.
 */
export function useDocumentLanguage(): void {
  const lang = useSettingsStore((s) => s.settings.lang);
  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = "ltr";
  }, [lang]);
}
